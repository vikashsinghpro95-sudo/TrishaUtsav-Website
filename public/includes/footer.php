    <script>
        document.addEventListener('DOMContentLoaded', async () => {
            // Highlight active mobile bottom navigation icon based on current page
            const path = window.location.pathname.toLowerCase();
            const navBtns = document.querySelectorAll('.mobile-nav-btn');
            
            navBtns.forEach(btn => {
                const target = btn.getAttribute('data-nav');
                if (
                    (target === 'index' && (path.endsWith('index.php') || path === '/' || path.endsWith('/public/'))) ||
                    (target === 'shop' && path.includes('shop.php') && !window.location.search.includes('sort=newest')) ||
                    (target === 'festive' && window.location.search.includes('sort=newest')) ||
                    (target === 'cart' && path.includes('cart.php')) ||
                    (target === 'account' && (path.includes('account.php') || path.includes('login.php')))
                ) {
                    btn.classList.remove('text-slate-400');
                    btn.classList.add('text-[#f59e0b]', 'bg-[#990024]/40', 'shadow-inner');
                }
            });

            // Update mobile cart badge count if available
            try {
                if (window.Cart && typeof window.Cart.getCount === 'function') {
                    const count = window.Cart.getCount();
                    const badge = document.getElementById('mobile-cart-badge');
                    if (badge && count > 0) {
                        badge.innerText = count;
                        badge.classList.remove('hidden');
                    }
                }
            } catch(e) {}

            try {
                const res = await Api.get('/settings');
                if (res.success && res.data) {
                    const d = res.data;
                    
                    // Logo or Store Name
                    if (d.store_logo) {
                        const logoBox = document.getElementById('footer-logo-box');
                        if (logoBox) {
                            logoBox.innerHTML = `
                                <a href="${BASE_URL}index.php" class="inline-block">
                                    <img src="${d.store_logo.startsWith('http') ? d.store_logo : BASE_URL + d.store_logo}" alt="${d.store_name || 'Store Logo'}" class="h-10 object-contain">
                                </a>
                            `;
                        }
                    } else if (d.store_name) {
                        const brandTitle = document.getElementById('footer-brand-title');
                        if (brandTitle) brandTitle.innerText = d.store_name;
                    }

                    // About Paragraph
                    if (d.footer_about_text) {
                        const p = document.getElementById('footer-about-paragraph');
                        if (p) p.innerText = d.footer_about_text;
                    }

                    // Mandala Background Pattern Toggle
                    const mandalaBg = document.getElementById('footer-mandala-bg');
                    if (mandalaBg && d.footer_decorations_enabled === 'false') {
                        mandalaBg.classList.add('hidden');
                    }

                    // Copyright String
                    if (d.footer_copyright_text) {
                        const copyEl = document.getElementById('footer-copyright-notice');
                        if (copyEl) copyEl.innerText = d.footer_copyright_text;
                    }
                }
            } catch (e) {}
        });
